import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { _electron } from 'playwright';
import { en, zh } from '../apps/desktop/src/renderer/messages.ts';
assert.deepEqual(Object.keys(en).sort(), Object.keys(zh).sort());
for (const key of Object.keys(zh)) {
  assert.ok(en[key].trim());
  assert.deepEqual(en[key].match(/\{\w+\}/g)?.sort(), zh[key].match(/\{\w+\}/g)?.sort(), key);
}
const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(path.join(root, 'apps/desktop/package.json'));
const dataDir = await mkdtemp(path.join(tmpdir(), 'siyue-i18n-'));
const output = path.join(root, 'artifacts/i18n');
await mkdir(output, { recursive: true });
const checks = ['bilingual key and interpolation completeness'];
let app;
async function start(locale) {
  app = await _electron.launch({ executablePath: require('electron'), args: [path.join(root, 'apps/desktop')], cwd: root, env: { ...process.env, SIYUE_DATA_DIR: dataDir, SIYUE_RENDERER_URL: '' }, chromiumSandbox: true });
  const page = await app.firstWindow();
  await page.getByText(locale === 'en' ? en.localAvailable : zh.localAvailable, { exact: true }).waitFor();
  return page;
}
async function switchTo(page, locale) {
  await page.locator('.settings-trigger').click();
  await page.getByRole('button', { name: locale === 'en' ? 'English' : '简体中文', exact: true }).click();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.settings-trigger').evaluate(el => el === document.activeElement), true);
}
try {
  let page = await start('zh-CN');
  await page.locator('#goal-input').fill('保留中文原文 Keep my input');
  await page.getByRole('button', { name: zh.createManual, exact: true }).click();
  await page.locator('#tasks').fill('任务一\nTask two');
  await switchTo(page, 'en');
  assert.equal(await page.locator('#goal-input').inputValue(), '保留中文原文 Keep my input');
  assert.equal(await page.locator('#tasks').inputValue(), '任务一\nTask two');
  assert.equal(await page.locator('html').getAttribute('lang'), 'en');
  await page.getByRole('button', { name: en.confirmManual, exact: true }).click();
  await page.getByText('Saved locally · 3 records.', { exact: true }).waitFor();
  await switchTo(page, 'zh-CN');
  await page.getByText('已保存到本机 · 3 条正式记录。', { exact: true }).waitFor();
  await switchTo(page, 'en');
  await page.getByRole('button', { name: en.complete, exact: true }).first().click();
  await page.getByRole('button', { name: en.undoComplete, exact: true }).waitFor();
  checks.push('language switch preserves manual inputs; English save/complete; existing notice translates; Escape restores focus');
  await page.reload();
  await page.getByText(en.localAvailable, { exact: true }).waitFor();
  await app.close(); app = undefined;
  page = await start('en');
  await page.getByRole('button', { name: en.undoComplete, exact: true }).waitFor();
  checks.push('English preference and completed task survive reload and full Electron restart');
  await page.locator('#goal-input').fill('Sample draft 原文');
  await page.getByRole('button', { name: en.generate, exact: true }).click();
  await page.getByRole('button', { name: en.confirmDraft, exact: true }).waitFor();
  await page.locator('#plan-title').fill('Edited draft 原文');
  await switchTo(page, 'zh-CN');
  assert.equal(await page.locator('#plan-title').inputValue(), 'Edited draft 原文');
  assert.equal(await page.getByRole('button', { name: zh.confirmDraft, exact: true }).isDisabled(), true);
  await switchTo(page, 'en');
  await page.getByRole('button', { name: en.saveDraft, exact: true }).click();
  await page.getByText(en.draftSaved, { exact: true }).waitFor();
  await page.getByRole('button', { name: en.reject, exact: true }).click();
  await page.getByText(en.draftRejected, { exact: true }).waitFor();
  await page.getByRole('button', { name: en.collapseEditor, exact: true }).click();
  checks.push('English sample draft and edited input survive switching; dirty guard, save and reject work');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(860, 640));
  await page.waitForFunction(() => innerWidth <= 900);
  await page.locator('.settings-trigger').click();
  await page.screenshot({ path: path.join(output, 'desktop-en-settings.png') });
  await page.keyboard.press('Escape');
  await page.screenshot({ path: path.join(output, 'desktop-en-workspace.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.setZoomFactor(2));
  await page.waitForFunction(() => innerWidth <= 450);
  await page.locator('.settings-trigger').click();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await writeFile(path.join(output, 'desktop-en-settings-200.png'), Buffer.from(await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toPNG())));
  assert.equal(await page.getByRole('button', { name: 'English', exact: true }).evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight; }), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.keyboard.press('Escape');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.setZoomFactor(1));
  await page.evaluate(() => localStorage.setItem('siyue.locale', 'unknown'));
  await page.reload();
  await page.getByText(zh.localAvailable, { exact: true }).waitFor();
  checks.push('unknown locale falls back to Chinese; 900x640 (native minimum) and 200% zoom have no horizontal overflow');
  await page.locator('.settings-trigger').click();
  await page.screenshot({ path: path.join(output, 'desktop-zh-settings.png') });
  await page.evaluate(() => { const set = Storage.prototype.setItem; Storage.prototype.setItem = function(k, v) { if(k === 'siyue.locale') throw new Error('synthetic storage failure'); return set.call(this,k,v); }; });
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await page.getByRole('alert').getByText(en.localeFailure, { exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'desktop-en-storage-failure.png') });
  assert.equal(await page.evaluate(() => localStorage.getItem('siyue.locale')), 'unknown');
  checks.push('storage failure switches session language, displays English failure, does not claim persistence');
  await writeFile(path.join(output, 'desktop-i18n.json'), JSON.stringify({ status: 'passed', checks, dataDir, runtime: await app.evaluate(() => process.versions) }, null, 2));
  console.log(JSON.stringify({ status: 'passed', checks }, null, 2));
} finally { if(app) await app.close(); }
