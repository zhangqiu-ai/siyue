/** Codes whose generic account wording would mislead a caller who already submitted a deletion. */
const overrides:Record<string,{zh:string;en:string}> = {
  operation_completed:{zh:'没有可重试的注销请求。',en:'There is no deletion request to retry.'},
  busy:{zh:'已有一份注销请求正在处理，请稍候。',en:'A deletion request is already in progress.'},
  challenge_invalid:{zh:'本机的进度回执已失效，或与服务器记录不匹配。',en:'The progress receipt on this device is spent or does not match the server.'},
  invalid_response:{zh:'服务端返回的注销数据无法识别，已停止操作。',en:'The deletion data returned by the service is not recognized; the operation stopped.'},
  storage_corrupt:{zh:'本机保存的注销回执无法读取，原件已保留。请联系思玥支持核实进度。',en:'The deletion receipt on this device cannot be read. The original is preserved; contact Siyue support.'},
  storage_unavailable:{zh:'安全存储写入失败，注销回执尚未保存。请解锁设备后重试。',en:'Secure storage could not save the deletion receipt. Unlock this device and retry.'},
};

export function deletionText(locale:string) { return locale==='en'?deletionEn:deletionZh; }
export function deletionErrorText(locale:string,code:string) {
  const override=overrides[code];
  if(override)return locale==='en'?override.en:override.zh;
  return authErrorText(locale,code);
}
