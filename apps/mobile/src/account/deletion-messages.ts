export function deletionText(locale:string):DeletionText {return locale==='en'?deletionEn:deletionZh;}
/** Fills `{name}` placeholders. An unknown placeholder stays visible instead of rendering `undefined`. */
export function fill(template:string,values:Record<string,string|number>={}):string {
  return template.replace(/\{(\w+)\}/g,(match,name)=>values[name]===undefined?match:String(values[name]));
}
