/** Same placeholder and number formatting as the shared catalogue. */
export function spaceTranslate(locale: Locale, key: SpaceMessageKey, params: Record<string, string | number> = {}): string {
  const message = locale === 'en' ? spaceEn[key] : spaceZh[key];
  return message.replace(/\{(\w+)\}/g, (match, name: string) => params[name] === undefined ? match
    : typeof params[name] === 'number' ? new Intl.NumberFormat(locale).format(params[name] as number) : String(params[name]));
}
